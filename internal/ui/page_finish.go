type finishPage struct {
	status   *widget.Label
	urlLink  *widget.Hyperlink
	openBtn  *widget.Button
	pwLabel  *widget.Label
	reveal   *widget.Check
	copyPw   *widget.Button
	ports    *widget.Label
	password string // kept in memory only, cleared by "Start over"
	url      string
}

func (z *wizard) pageFinish() fyne.CanvasObject {
	f := &z.fin
	f.status = widget.NewLabel("")
	f.status.Wrapping = fyne.TextWrapWord
	u, _ := url.Parse("http://localhost")
	f.urlLink = widget.NewHyperlink("", u)
	f.openBtn = widget.NewButtonWithIcon("Open the web console", theme.ComputerIcon(), func() {
		if pu, err := url.Parse(f.url); err == nil {
			_ = z.a.OpenURL(pu)
		}
	})
	f.openBtn.Importance = widget.HighImportance
	f.pwLabel = widget.NewLabel("")
	f.reveal = widget.NewCheck("Show", func(bool) { z.renderPassword() })
	f.copyPw = widget.NewButtonWithIcon("Copy", theme.ContentCopyIcon(), func() { z.a.Clipboard().SetContent(f.password) })
	f.ports = widget.NewLabel("")
	f.ports.Wrapping = fyne.TextWrapWord

	doctor := widget.NewButtonWithIcon("Run a health check (dune doctor)", theme.ConfirmIcon(), z.runHealthCheck)
	again := widget.NewButton("Start over", z.startOver)
	return container.NewVScroll(container.NewVBox(
		heading("Your server is ready", 24),
		f.status,
		widget.NewCard("Web console", "Manage players, maps, backups and settings in your browser", container.NewVBox(f.urlLink, f.openBtn)),
		widget.NewCard("Admin password", "Generated by Dune Docker; change it later in the console settings",
			container.NewBorder(nil, nil, nil, container.NewHBox(f.reveal, f.copyPw), f.pwLabel)),
		widget.NewCard("Before players can join", "Ports to open in your router and firewall", container.NewVBox(f.ports,
			container.NewHBox(link("Router & firewall guide", urlRouter), link("Official networking docs", urlDocs)))),
		container.NewHBox(doctor, again),
	))
}

func (z *wizard) renderPassword() {
	f := &z.fin
	switch {
	case f.password == "":
		f.pwLabel.SetText("(not available - read runtime/secrets/admin-web-password.txt on the server)")
	case f.reveal.Checked:
		f.pwLabel.SetText(f.password)
	default:
		f.pwLabel.SetText(strings.Repeat("•", 12))
	}
	if f.password == "" {
		f.copyPw.Disable()
	} else {
		f.copyPw.Enable()
	}
}

// showFinish switches to the final page and loads address and password.
func (z *wizard) showFinish() {
	f := &z.fin
	req := z.request()
	cfg := req.Cfg()
	port := z.ins.port
	if port == 0 {
		port = cfg.WebPort
	}
	f.status.SetText("The installation finished. Sietches, Deep Desert and tuning have been applied. Keep this window open until you have noted the password below.")
	f.ports.SetText(portsText(port, cfg.ConfigureFirewall))
	f.password = ""
	f.reveal.SetChecked(false)
	z.renderPassword()
	f.url = fmt.Sprintf("http://%s:%d", hostForURL(cfg.SSH.Host, cfg.Target == "ssh"), port)
	if pu, err := url.Parse(f.url); err == nil {
		f.urlLink.SetText(f.url)
		f.urlLink.SetURL(pu)
	}
	z.show(pgFinish)
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
		defer cancel()
		info, err := z.c.FinishInfo(ctx, req, port)
		fyne.Do(func() {
			if info.URL != "" {
				f.url = info.URL
				if pu, perr := url.Parse(info.URL); perr == nil {
					f.urlLink.SetText(info.URL)
					f.urlLink.SetURL(pu)
				}
			}
			f.password = info.Password
			z.renderPassword()
			if err != nil {
				f.status.SetText(f.status.Text + "\n\n" + err.Error())
			}
		})
	}()
}

func hostForURL(host string, remote bool) string {
	if !remote || host == "" {
		return "localhost"
	}
	return host
}

func portsText(consolePort int, firewallDone bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "UDP %s   game traffic\nUDP %s   optional direct latency checks\nTCP %d, %d   game messaging\nTCP %d   web console (trusted administrators only!)\n",
		strings.Replace(install.GamePorts.UDPGame, ":", "-", 1), strings.Replace(install.GamePorts.UDPProbe, ":", "-", 1),
		install.GamePorts.TCPGame[0], install.GamePorts.TCPGame[1], consolePort)
	if firewallDone {
		b.WriteString("\nThe server firewall (ufw/firewalld) was opened for these ports. Your router and any cloud firewall still need the rules.")
	} else {
		b.WriteString("\nOpen them in the server firewall, any cloud firewall / security group and forward them in your router. Never expose the database or Docker.")
	}
	return b.String()
}

func (z *wizard) runHealthCheck() {
	z.runActionDialog("status", "Health check")
}

// startOver clears everything sensitive from memory and returns to the start.
func (z *wizard) startOver() {
	z.fin.password = ""
	z.fin.pwLabel.SetText("")
	z.srv.token.SetText("")
	z.tgt.pass.SetText("")
	z.tgt.phrase.SetText("")
	z.ins.accept.SetChecked(false)
	z.scn.scanned = false
	z.show(pgWelcome)
	dialog.ShowInformation("Cleared", "Your token and passwords were removed from memory.", z.w)
}
